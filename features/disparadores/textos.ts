/** The text for `clave` in `idioma` (fallback: English), with `{x}` filled from `vars`. Pure; never throws, never empty for a known key. */
export function textoDisparadores(idioma: string | undefined, clave: string, vars: Readonly<Record<string, string | number>> = {}): string {
  const l = idioma ?? IDIOMA_DISPARADORES;
  const t = TEXTOS_DISPARADORES[l]?.[clave] ?? TEXTOS_DISPARADORES.en[clave] ?? clave;
  return t.replace(/\{(\w+)\}/g, (_, k: string) => (Object.hasOwn(vars, k) ? String(vars[k]) : `{${k}}`));
}
