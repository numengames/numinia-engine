#!/usr/bin/env node
// Generates apps/plaza/novedades-datos.ts from docs/RUNLOG.md + the pending .changeset/*.md fragments + package.json:
// the 3 most recent diary entries' «Qué» line, baked into the bundle at build time so the browser never downloads the
// diary (t_bdc2c2db). The pending fragments count as the newest entries: a change is news from the moment it is on main,
// before the release PR has folded it into the diary and moved the version.
// The file is NOT in git (.gitignore): it is made from the diary, so two pull requests never fight over it. It is
// regenerated before dev/build/test (hooks in package.json), by the vite config (every build, however it is started)
// and by the strict-types gate (tools/tipos.ts). By hand: `npm run novedades`.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { novedadesDeRunlog } from "../packages/client/src/novedades.ts";
import { anadirARunlog, leerFragmentos } from "./lib/cambios.mjs";

/** Writes `<raiz>/apps/plaza/novedades-datos.ts` (only when its text changed, so a watcher is not woken for nothing).
 * Returns { version, items, escrito }. A broken fragment is skipped with a warning: the test names it, the build still works. */
export function generarNovedades(raiz, { silencio = false } = {}) {
  const version = JSON.parse(readFileSync(join(raiz, "package.json"), "utf8")).version;
  let diario = readFileSync(join(raiz, "docs/RUNLOG.md"), "utf8");
  let pendientes = [];
  try { pendientes = leerFragmentos(join(raiz, ".changeset")); } catch (e) { if (!silencio) console.warn(`[novedades] fragmento ignorado: ${e.message}`); }
  diario = anadirARunlog(diario, pendientes);
  const items = novedadesDeRunlog(diario, 3);
  const out = `// Generated by tools/novedades-generar.mjs from docs/RUNLOG.md, .changeset/ and package.json — do not edit by hand, it is not in git.
// Regenerate it with \`npm run novedades\` (it also runs before "dev", "build" and "test").
/** The engine version when this file was generated (only for whoever reads it; the real comparison is done by
 * apps/plaza/novedades.ts against the version of the package running the page). */
export const version = ${JSON.stringify(version)};
/** Up to 3 lines, newest first. Empty if the diary had no entry with «Qué». */
export const items: readonly string[] = ${JSON.stringify(items, null, 2)};
`;
  const destino = join(raiz, "apps/plaza/novedades-datos.ts");
  const escrito = !existsSync(destino) || readFileSync(destino, "utf8") !== out;
  if (escrito) writeFileSync(destino, out);
  if (!silencio) console.log(`[novedades] ${items.length} novedades para v${version} (${pendientes.length} fragmento(s) pendiente(s)) ${escrito ? "escritas en" : "ya estaban en"} apps/plaza/novedades-datos.ts`);
  return { version, items, escrito };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  generarNovedades(fileURLToPath(new URL("..", import.meta.url)));
}
