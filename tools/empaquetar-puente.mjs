// empaquetar-puente (M1, remote MCP): bundles the world bridge for a host that is not Node (a Cloudflare Worker / Durable
// Object: numinia-web apps/mcp «Cuerpo») into ONE ES module, dist/puente-mundo.mjs, with platform «neutral»: no Node
// built-ins are resolved, and any import the bundle cannot resolve (a `node:…`, a bare package) FAILS the build instead of
// being left as an external import. Entry: packages/agent/src/puente-neutral.ts. Bundler: rolldown, the one vite 8 already
// brings (no new dependency). Not minified, so whoever copies it can read it; the size printed is what a Worker uploads.
//   npm run puente            (or: node tools/empaquetar-puente.mjs [--salida <file>])
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { build } from "rolldown";

const raiz = join(fileURLToPath(import.meta.url), "../..");
export const ENTRADA = join(raiz, "packages/agent/src/puente-neutral.ts");
export const SALIDA = join(raiz, "dist/puente-mundo.mjs");

/** Every module specifier the bundle still imports (static, dynamic or require): an empty list = self-contained. */
export function importsDe(codigo) {
  const r = new Set();
  for (const m of codigo.matchAll(/\b(?:import|export)\s*(?:[\w*{}\s,$]*?\bfrom\s*)?["']([^"']+)["']|\bimport\s*\(\s*["']([^"']+)["']\s*\)|\brequire\s*\(\s*["']([^"']+)["']\s*\)/g)) r.add(m[1] ?? m[2] ?? m[3]);
  return [...r];
}

/** Bundles the bridge; returns the code (and writes it when `salida` is given). Throws on any unresolved import.
 * `entrada` = another entry (tests: a Node-only file must fail). */
export async function empaquetarPuente({ salida, entrada = ENTRADA } = {}) {
  const version = JSON.parse(readFileSync(join(raiz, "package.json"), "utf8")).version;
  const problemas = [];
  const r = await build({
    input: entrada, platform: "neutral", write: false, logLevel: "warn",
    onLog: (nivel, log) => { if (log.code === "UNRESOLVED_IMPORT" || nivel === "warn") problemas.push(log.message); },
    output: { format: "esm", banner: `// numinia-engine ${version} · puente-mundo (packages/agent/src/puente-neutral.ts) · AGPL-3.0-only · generated by tools/empaquetar-puente.mjs: do not edit` },
  });
  if (problemas.length) throw new Error(`el puente no se empaqueta limpio (plataforma neutral):\n${problemas.join("\n")}`);
  const trozos = r.output.filter((o) => o.type === "chunk");
  if (trozos.length !== 1) throw new Error(`esperaba un solo fichero y salen ${trozos.length}`);
  const codigo = trozos[0].code, fuera = importsDe(codigo);
  if (fuera.length) throw new Error(`el paquete aún importa cosas de fuera: ${fuera.join(", ")}`);
  if (salida) { mkdirSync(dirname(salida), { recursive: true }); writeFileSync(salida, codigo); }
  return { codigo, bytes: Buffer.byteLength(codigo), gz: gzipSync(codigo).length, version };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const i = process.argv.indexOf("--salida"), salida = i > 0 ? resolve(process.argv[i + 1]) : SALIDA;
  try {
    const p = await empaquetarPuente({ salida });
    console.log(`puente-mundo ${p.version} → ${salida}: ${(p.bytes / 1000).toFixed(1)} kB (${(p.gz / 1000).toFixed(1)} kB gz), sin imports de fuera`);
  } catch (e) { console.error(String(e.message ?? e)); process.exit(1); }
}
